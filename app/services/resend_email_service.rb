  # Sends an AI-composed email (subject + body already generated by Claude).
  # Returns { success:, message_id:, error: }.
  def self.send_composed(to:, subject:, body_text:, body_html: nil)
    api_key = ENV['RESEND_API_KEY']
    raise 'RESEND_API_KEY not set' unless api_key

    html = body_html || plain_to_html(body_text)
    payload = {
      from:    FROM,
      to:      Array(to),
      cc:      CC,
      subject: subject,
      html:    html,
      text:    body_text
    }

    response = post_json(payload, api_key)
    if response && response['id']
      { success: true, message_id: response['id'] }
    else
      { success: false, error: response.inspect }
    end
  rescue StandardError => e
    { success: false, error: e.message }
  end

