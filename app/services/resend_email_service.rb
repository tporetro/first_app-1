  def self.plain_to_html(text)
    # Wrap plain text in minimal HTML preserving line breaks
    escaped = text.gsub('&', '&amp;').gsub('<', '&lt;').gsub('>', '&gt;')
    paragraphs = escaped.split(/\n{2,}/).map { |p| "<p>#{p.gsub("\n", '<br>')}</p>" }.join("\n")
    "<div style=\"font-family:Arial,sans-serif;max-width:600px;color:#222;line-height:1.6;\">#{paragraphs}</div>"
  end

  def self.post_json(payload, api_key)
    uri  = URI.parse(API_URL)
    http = Net::HTTP.new(uri.host, uri.port)
    http.use_ssl = true
    req = Net::HTTP::Post.new(uri.path)
    req['Authorization'] = "Bearer #{api_key}"
    req['Content-Type']  = 'application/json'
    req.body = payload.to_json
    resp = http.request(req)
    JSON.parse(resp.body)
  end
